//! This module contains the lowering of Immediate-Parsed-Representation (IPR) into Typed-Highlevel-Representation (THR)
//! The main difference between these two is that IPR is a tree,
//! whereas THR is flat and has a bunch of interning tables that hold its nodes.
//! Instead of [`Box`]'es,
//! you have indices into the interning tables.
//!
//! The interning tables are instatiations of the [`KeySet<Key, Value>`] generic type,
//! which is itself an ergonomic wrapper around an [`IndexSet`].
//! The `Key` is often a newtype wrapper around [`usize`].
//!
//!
//! The two structs that play a key role in the lowering process are [`THRKeySets`] and [`IPRLoweringContext`]:
//! - [`IPRLoweringContext`] contains an [`IPRModule`] along with all the hashmaps generated by visitor passes,
//!   like type information, identifier resolution etc., everything necessary to infer all properties of a given node.
//! - [`THRKeySets`] contains a bunch of interning tables for :
//!     - types
//!     - symbols
//!     - expressions
//!     - statements
//!     - control-flow-blocks.
//!
//! An [`IPRModule`] can be lowered into THR by using the [`lower_module`] function,
//! which (should be?) infallible
//! as every prior visitor pass validates some set of properties of the AST.
//!
//! the [`lower_module`] call will construct an [`THRModule`], which contains the [`THRKeySets`],
//! and the ID of the synthesized block that instantiate the global variables.
//!
//! Any `lower_[node]()` method of the [`THRKeySets`] will guarantee the following:
//! - After the call returns, all descendant nodes of the supplied node will be interned
//! - An ID (or ID's) will be returned which points to the lowered version of the supplied node.
//!
//! The returned ID is used for constructing nodes wihch hold references,
//! like the `.value` or `.symbol` field in an [`THRInit`].
//!
//! At this stage, structs are also lowered into [`THRStructLayout`]'s,
//! from which you can get byte-offsets for fields, their size and alignment.
//!
//! What the THR does not directly provide is a control flow graph (CFG),
//! This is done by a later visitor pass,
//! which provides a way to get the pred- and successors of a [`THRBlock`],
//! which is then used by QBE or some other backend to generate its CFG.
//!
//! Since Zea is a value-oriented language, most constructs  evaluate to some kind of value.
//! a block `{ var := val; var }` would evaulate to whatever `val` is,
//! while `{ var := val; }` evaluates to `()`.
//! likewise a branch `if cond { val1 } else { val2 }`
//! (with `var1` and `var2` having the same type) would evaluate to
//! one of the two `val`'s depending on `cond`. Each value-full construct emits a [`THRInit`]
//! that assigns the constructs value to a syhnthesized, unique label like `IPR.N`
//! or something similar (I will decide on that later)
//!
//! So the code
//! ```
//! a := { var := 3; var};
//! ```
//!
//! lowers into:
//! ```
//! @IPR.0
//!   %var := 3;
//!   %IPR.0 := var;
//! # end of the block
//!   %a := IPR.0;
//! ```
//!
//! The methods that THRKeySets defines lower IPR constructs
//! into THR ones.
//!
//! THR maps quite closely to QBE-IL, and as such a lot of 'desugaring' must be done.
//! For example, We cannot have initializors for a variable `v` be blocks or branches anymore,
//! instead we must synthesize a temporary `t` and assign to it within the lowered construct,
//! and then assign that synthesized temporary to `v`:
//! ```
//! a := 3;
//! b := if a < 10 {
//!   6
//! } else {
//!   7
//! };
//! c := b + 4;
//!
//! # could become
//! %a : U8 = constint(3);
//! %t0: Bool = %a;
//! jnz %t0, @IPR.0.t, @IPR.0.nt;
//!
//! @IPR.0.t:
//! %IPR.0: U8 = 6;
//! jmp @IPR.0.m;
//!
//! @IPR.0.nt:
//! %IPR.0: U8 = 7;
//! jmp @IPR.0.m;
//!
//! @IPR.0.m:
//! %b : U8 = %IPR.0;
//! %t1 : U8 = constint(4);
//! %c : U8 = add %b, %t1
//! ```
//!
//! This lowering is quite naive and can be optimized of course, but this is quite
//! close to how the current implementation would lower this code.
//!
//!
//! Most methods return something like [`(Vec<THRStatementID>, THRStatementID)`],
//! [`(Vec<THRStatementID>, THRExprID)`], etc. The first return value `pre` of the tuple contains
//! all the statements needed to compute the second tuple value `val`.
//!
//! i.e. when lowering a binary expression, we would concatenate the `pre`'s of the operands,
//! and then emit an `add` intruction of their `val`'s:
//! ```Rust
//! // given (assignee, l, r, op)
//! let (l_pre, l_val, l_val_t) = lower_expr(l);
//! let (r_pre, r_val, r_val_t) = lower_expr(r);
//! l_pre.extend(r_pre);
//! let val = make_binop(op, l_val, r_val);
//! let init = make_init(assignee, val);
//! l_pre.push(init);
//! ```

