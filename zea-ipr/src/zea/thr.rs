//! This module contains the lowering of Immediate-Parsed-Representation (IPR) into Typed-Highlevel-Representation (THR)
//! The main difference between these two is that IPR is a tree of [`Box`]'es,
//! whereas THR has a bunch of interning tables that hold its nodes, and instead of [`Box`]'es,
//! you have indices into the interning tables.
//!
//! The interning tables are instatiations of the [`InternTable<Key, Value>`] generic type,
//! which is itself an ergonomic wrapper around an [`IndexSet`].
//! The `Key` is often a newtype wrapper around [`usize`].
//!
//!
//! The two structs that play a key role in the lowering process are [`THRInternTables`] and [`IPRLoweringContext`]:
//! - [`IPRLoweringContext`] contains an [`IPRModule`] along with all the hashmaps generated by visitor passes,
//!   like type information, identifier resolution etc., everything necessary to infer all properties of a given node.
//! - [`THRInternTables`] contains a bunch of interning tables for :
//!     - types
//!     - symbols
//!     - expressions
//!     - statements
//!     - control-flow-blocks.
//!
//! An [`IPRModule`] can be lowered into THR by using the [`lower_module`] function,
//! which (should be?) infallible
//! as every prior visitor pass validates some set of properties of the AST.
//!
//! the [`lower_module`] call will construct an [`THRModule`], which contains the [`THRInternTables`],
//! and the ID of the synthesized block that instantiate the global variables.
//!
//! Any `lower_[node]()` method of the [`THRInternTables`] will guarantee the following:
//! - After the call returns, all descendant nodes of the supplied node will be interned
//! - An ID (or ID's) will be returned which points to the lowered version of the supplied node.
//!
//! The returned ID is used for constructing nodes wihch hold references,
//! like the `.value` or `.symbol` field in an [`THRInit`].
//!
//! At this stage, structs are also lowered into [`THRStructLayout`]'s,
//! from which you can get byte-offsets for fields, their size and alignment
//!
//! What the THR does not directly provide is a control flow graph (CFG),
//! This is done by a later visitor pass, which provides a way to get the pred- and successors of a [`THRBlock`],
//! which is then used by QBE or some other backend to generate its CFG.

