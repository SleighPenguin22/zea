#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum IntegerWidth {
    _8 = 1,
    _16 = 2,
    _32 = 4,
    _64 = 8,
}

impl TryFrom<usize> for IntegerWidth {
    type Error = usize;
    fn try_from(value: usize) -> Result<Self, Self::Error> {
        match value {
            8 => Ok(Self::_8),
            16 => Ok(Self::_16),
            32 => Ok(Self::_32),
            64 => Ok(Self::_64),
            _ => Err(value),
        }
    }
}

